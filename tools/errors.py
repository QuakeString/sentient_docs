"""Builds the error catalogue pages from data/errors.yml.

One page per error at content/docs/troubleshooting/errors/<id>.md, plus the
section index with one table per area. Run after editing data/errors.yml:

    python3 tools/errors.py

The pages are generated: edit the YAML, not the Markdown.
"""
import html
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "errors.yml"
OUT = ROOT / "content" / "docs" / "troubleshooting" / "errors"
HEADER = "<!-- Generated by tools/errors.py from data/errors.yml. Do not edit. -->\n"


def inline(s: str) -> str:
    """Plain text with `code`, for the HTML fact boxes."""
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", html.escape(s))


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def page(e: dict, area: dict, weight: int, checked: str) -> str:
    eid = e["id"]
    lines = [
        "+++",
        f"title = {q(eid + ' ' + e['title'])}",
        f"description = {q(e['summary'])}",
        f"weight = {weight}",
        "",
        "[extra]",
        'status = "checked"',
        f"checked = {q(e.get('checked', checked))}",
        f"error_id = {q(eid)}",
        "+++",
        HEADER,
    ]
    facts = [("Error ID", eid), ("Area", area["title"])]
    if e.get("http"):
        facts.append(("HTTP status", str(e["http"])))
    if e.get("code") is not None:
        facts.append(("API error code", str(e["code"])))
    if e.get("where"):
        facts.append(("Where you see it", e["where"]))
    lines.append('<div class="facts">' + "".join(
        f'<div class="fact{" wide" if k == "Where you see it" else ""}"><small>{k}</small><b>{inline(v)}</b></div>' for k, v in facts) + "</div>\n")
    for m in e.get("messages") or []:
        lines.append(f'<div class="msg"><small>Message</small><span>{html.escape(m.strip())}</span></div>\n')
    lines.append("## Why it happens\n")
    lines.append(e["cause"].rstrip() + "\n")
    lines.append("## Fix it\n")
    lines.append(e["fix"].rstrip() + "\n")
    if e.get("check"):
        lines.append("## Check that it worked\n")
        lines.append(e["check"].rstrip() + "\n")
    rel = [r.split("|", 1) for r in e.get("related") or []]
    rel = rel + [["Error catalogue", "/docs/troubleshooting/errors/"]]
    lines.append("## Related\n")
    lines += [f"- [{t}]({u})" for t, u in rel]
    return "\n".join(lines) + "\n"


def main() -> int:
    data = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    checked = data["checked"]
    OUT.mkdir(parents=True, exist_ok=True)
    seen, written = set(), set()
    index = [
        "+++",
        'title = "Error catalogue"',
        "description = " + q("Every SENTIENT error with its own page: the message, why it happens and how to fix it. Search by the error ID or by the words of the message."),
        f"weight = {data.get('weight', 184)}",
        "",
        "[extra]",
        'status = "checked"',
        f"checked = {q(checked)}",
        "hide_children = true",
        "+++",
        HEADER,
        data["intro"].rstrip() + "\n",
    ]
    w = 0
    for area in data["areas"]:
        index.append(f"## {area['title']}\n")
        if area.get("intro"):
            index.append(area["intro"].rstrip() + "\n")
        index.append("| ID | Error |\n|---|---|")
        for e in area["errors"]:
            eid = e["id"]
            if eid in seen:
                print(f"duplicate id {eid}", file=sys.stderr)
                return 1
            seen.add(eid)
            w += 1
            slug = eid.lower()
            (OUT / f"{slug}.md").write_text(page(e, area, w, checked), encoding="utf-8")
            written.add(f"{slug}.md")
            index.append(f"| [{eid}](/docs/troubleshooting/errors/{slug}/) | [{e['title']}](/docs/troubleshooting/errors/{slug}/) |")
        index.append("")
    (OUT / "_index.md").write_text("\n".join(index), encoding="utf-8")
    for old in OUT.glob("*.md"):
        if old.name != "_index.md" and old.name not in written:
            old.unlink()
    print(f"wrote {len(written)} error pages to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
