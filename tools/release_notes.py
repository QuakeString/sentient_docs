"""Writes content/docs/reference/release-notes.md from SENTIENT's CHANGELOG.md.

    python3 tools/release_notes.py ../SENTIENT/CHANGELOG.md

Run it after each SENTIENT release. Only released versions are written
(not [Unreleased]). PR links are dropped, as in the public release notes,
because the source repositories are private.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "content" / "docs" / "reference" / "release-notes.md"
HEADING = re.compile(r"^## \[(?P<v>[^\]]+)\](?: [-–—] (?P<date>\S+))?\s*$")
PR_LINK = r"\[#\d+\]\([^)]*\)"
PR_PAREN = re.compile(r"\s*\((?:" + PR_LINK + r"|[\s,]|\band\b|\bto\b)+\)")


def sections(text):
    cur, out = None, []
    for line in text.splitlines():
        m = HEADING.match(line)
        if m:
            cur = {"v": m.group("v"), "date": m.group("date"), "lines": []}
            out.append(cur)
        elif re.match(r"^\[[^\]]+\]:\s", line):
            cur = None
        elif cur is not None:
            cur["lines"].append(line)
    return [s for s in out if s["v"].lower() != "unreleased"]


def public(body):
    body = PR_PAREN.sub("", body)
    body = re.sub(r"\s*" + PR_LINK, "", body)
    body = re.sub(r"^Built from master `[0-9a-f]+`\.\s*$\n?", "", body, flags=re.M)
    body = re.sub(r"^### ", "#### ", body, flags=re.M)
    # The docs never name the upstream product (tools/check.py flags it).
    body = re.sub(r"\s+instead of ThingsBoard", "", body)
    body = re.sub(r"no longer say ThingsBoard", "say SENTIENT", body)
    return re.sub(r"\n{3,}", "\n\n", body).strip()


def main():
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    secs = sections(Path(sys.argv[1]).read_text(encoding="utf-8"))
    head = OUT.read_text(encoding="utf-8").split("+++")[1] if OUT.exists() else None
    front = "+++" + head + "+++\n" if head else '+++\ntitle = "Release notes"\n+++\n'
    front = re.sub(r'status = "[a-z]+"', 'status = "checked"', front)
    front = re.sub(r'\nwave = "[^"]*"', "", front)
    if "checked = " not in front:
        front = front.replace('status = "checked"', f'status = "checked"\nchecked = "{secs[0]["v"]}"')
    else:
        front = re.sub(r'checked = "[^"]*"', f'checked = "{secs[0]["v"]}"', front)
    body = [
        "<!-- Generated by tools/release_notes.py from SENTIENT's CHANGELOG.md. Do not edit. -->\n",
        "What changed in each SENTIENT release, newest first. Downloads for every release (Windows and Linux packages, "
        "the mobile app and the gateway) are on the [SENTIENT release page](https://github.com/QuakeString/sentient-release/releases); "
        "the Docker image is `quakestring/sentient:<version>`. To update, see [Upgrade and roll back](/docs/operations/upgrade/).\n",
    ]
    for s in secs:
        date = f" ({s['date']})" if s["date"] else ""
        body.append(f"## {s['v']}{date}\n")
        body.append(public("\n".join(s["lines"])) + "\n")
    OUT.write_text(front + "\n".join(body), encoding="utf-8")
    print(f"wrote {len(secs)} releases to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
